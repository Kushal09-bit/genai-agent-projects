def render_sidebar():
    with st.sidebar:
        st.subheader("Session: ID")
        st.code(st.session_state.session_id, language=None)
        st.caption(f"{len(st.session_state.history)} question(s) asked this session")

        with st.expander("View session history", expanded=True):
            if not st.session_state.history:
                st.caption("No questions asked yet.")
            for i, turn in enumerate(st.session_state.history, 1):
                st.write(f"**{i}.** {turn['question']}")
                st.caption(f"Trace ID: `{turn['result']['trace_id']}`")
                st.divider()

        st.divider()

        if st.button("Clear conversation"):
            st.session_state.history = []
            st.session_state.session_id = new_session_id()
            st.rerun()


def _extract_from_messages(result: dict):
    """Pull the SQL, columns, and rows out of the agent's tool call messages, if any."""
    final_sql, columns, rows, note = None, None, None, ""
    for msg in result.get("messages", []):
        if getattr(msg, "name", None) == "execute_sql" and isinstance(msg.content, str):
            content = msg.content
            if content.startswith("INVALID") or content.startswith("EXECUTION_ERROR"):
                continue
            try:
                data = json.loads(content)
                final_sql = data.get("sql")
                columns = data.get("columns")
                rows = data.get("rows")
                note = data.get("note", "")
            except (json.JSONDecodeError, TypeError):
                pass
    return final_sql, columns, rows, note


def _extract_final_answer(result: dict) -> str:
    """Find the last AI message in the returned message list — that's the final answer."""
    for msg in reversed(result.get("messages", [])):
        if getattr(msg, "type", None) == "ai" and msg.content:
            return msg.content
    return ""


def run_pipeline(question: str) -> dict:
    trace_id = new_trace_id()
    session_id = st.session_state.session_id
    log_event(component="pipeline", event="input_received", trace_id=trace_id, session_id=session_id, question=question)

    valid, reason = input_guardrail.check(question)
    log_event(component="input_guardrail", event="guardrail_checked", trace_id=trace_id, session_id=session_id, valid=valid, reason=reason)
    if not valid:
        return {"status": "blocked", "message": reason, "trace_id": trace_id, "sql": None}

    try:
        result = agent_executor.invoke(
            {"messages": [("user", question)]},
            config={
                "configurable": {"thread_id": session_id},
                "callbacks": [langfuse_handler],
            },
        )
    except Exception as e:
        import traceback
        error_details = traceback.format_exc()
        log_event(component="agent", event="agent_error", trace_id=trace_id, session_id=session_id, error=str(e), traceback=error_details)
        return {
            "status": "error",
            "message": "I couldn't process this question. Please try rephrasing.",
            "trace_id": trace_id,
            "sql": None,
        }

    final_sql, columns, rows, note = _extract_from_messages(result)
    final_answer = _extract_final_answer(result)

    log_event(
        component="agent",
        event="response_returned",
        trace_id=trace_id,
        session_id=session_id,
        answer=final_answer,
        sql=final_sql,
    )

    return {
        "status": "ok",
        "message": final_answer,
        "sql": final_sql,
        "columns": columns,
        "rows": rows,
        "trace_id": trace_id,
        "caveat": note,
    }


def render_result(r):
    if r["status"] == "ok":
        if r.get("caveat"):
            st.info(r["caveat"])
        st.write(r["message"])
        if r.get("rows") is not None and r.get("columns") is not None:
            st.dataframe([dict(zip(r["columns"], row)) for row in r["rows"]], use_container_width=True)
        if r.get("sql"):
            with st.expander("View generated SQL"):
                st.code(r["sql"], language="sql")
    elif r["status"] == "blocked":
        st.error(f"This request was blocked: {r['message']}")
    elif r["status"] == "no_answer":
        st.warning(f"I can't answer that: {r['message']}")
    else:
        st.warning(r["message"])
    st.caption(f"Trace ID: `{r['trace_id']}`")


