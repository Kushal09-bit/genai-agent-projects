def run_pipeline(question: str, max_retries: int = 2) -> dict:
    trace_id = new_trace_id()
    session_id = st.session_state.session_id
    log_event(component="pipeline", event="input_received", trace_id=trace_id, session_id=session_id, question=question)

    valid, reason = input_guardrail.check(question)
    log_event(component="input_guardrail", event="guardrail_checked", trace_id=trace_id, session_id=session_id, valid=valid, reason=reason)
    if not valid:
        return {"status": "blocked", "message": reason, "trace_id": trace_id, "sql": None}

    error_feedback = None
    for attempt in range(max_retries + 1):
        gen_result = generate(question, error_feedback, callbacks=[langfuse_handler])
        sql = gen_result["sql"]
        sql_tokens = {"input": gen_result["input_tokens"], "output": gen_result["output_tokens"]}
        log_event(component="nl_to_sql_chain", event="sql_generated", trace_id=trace_id, session_id=session_id, attempt=attempt + 1, sql=sql, input_tokens=sql_tokens["input"], output_tokens=sql_tokens["output"])

        if sql.startswith("NO_ANSWER"):
            log_event(component="nl_to_sql_chain", event="no_answer", trace_id=trace_id, session_id=session_id, reason=sql)
            return {"status": "no_answer", "message": sql.replace("NO_ANSWER:", "").strip(), "trace_id": trace_id, "sql": None}

        valid, reason = validator.validate(sql)
        log_event(component="sql_validator", event="validation_checked", trace_id=trace_id, session_id=session_id, valid=valid, reason=reason)
        if not valid:
            error_feedback = reason
            continue

        valid, reason, sql = output_guardrail.check(sql)
        log_event(component="output_guardrail", event="guardrail_checked", trace_id=trace_id, session_id=session_id, valid=valid, reason=reason, final_sql=sql)
        if not valid:
            error_feedback = reason
            continue

        try:
            with extractor.engine.connect() as conn:
                result = conn.execute(text(sql))
                columns = list(result.keys())
                rows = result.fetchall()
        except Exception as e:
            log_event(component="sql_execution", event="execution_error", trace_id=trace_id, session_id=session_id, error=str(e))
            return {"status": "error", "message": "The query could not be executed. Please try rephrasing.", "trace_id": trace_id, "sql": sql}

        log_event(component="sql_execution", event="query_executed", trace_id=trace_id, session_id=session_id, row_count=len(rows))

        columns, rows, sanitizer_note = result_sanitizer.sanitize(columns, rows)
        if sanitizer_note:
            log_event(component="result_sanitizer", event="results_sanitized", trace_id=trace_id, session_id=session_id, note=sanitizer_note)

        ans_result = answer(question, columns, rows, callbacks=[langfuse_handler])
        final_answer = ans_result["answer"]
        answer_tokens = {"input": ans_result["input_tokens"], "output": ans_result["output_tokens"]}
        log_event(component="answer_chain", event="response_returned", trace_id=trace_id, session_id=session_id, answer=final_answer, input_tokens=answer_tokens["input"], output_tokens=answer_tokens["output"])

        return {
            "status": "ok",
            "message": final_answer,
            "sql": sql,
            "columns": columns,
            "rows": rows,
            "trace_id": trace_id,
            "caveat": sanitizer_note,
            "tokens": {
                "sql_input": sql_tokens["input"],
                "sql_output": sql_tokens["output"],
                "answer_input": answer_tokens["input"],
                "answer_output": answer_tokens["output"],
            },
        }

    log_event(component="pipeline", event="max_retries_exceeded", trace_id=trace_id, session_id=session_id, question=question)
    return {"status": "error", "message": "I couldn't generate a valid, safe query after multiple attempts. Please try rephrasing your question.", "trace_id": trace_id, "sql": None}


def render_result(r):
    if r["status"] == "ok":
        if r.get("caveat"):
            st.info(r["caveat"])
        st.write(r["message"])
        if r.get("rows") is not None:
            st.dataframe([dict(zip(r["columns"], row)) for row in r["rows"]], use_container_width=True)
        with st.expander("View generated SQL"):
            st.code(r["sql"], language="sql")
        if r.get("tokens"):
            t = r["tokens"]
            total_in = t["sql_input"] + t["answer_input"]
            total_out = t["sql_output"] + t["answer_output"]
            st.caption(f"Tokens — input: {total_in}, output: {total_out}")
    elif r["status"] == "blocked":
        st.error(f"This request was blocked: {r['message']}")
    elif r["status"] == "no_answer":
        st.warning(f"I can't answer that: {r['message']}")
    else:
        st.warning(r["message"])
    st.caption(f"Trace ID: `{r['trace_id']}`")


